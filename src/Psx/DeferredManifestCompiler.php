<?php

declare(strict_types=1);

namespace Polidog\Rosanna\Psx;

use Polidog\Rosanna\Runtime\FunctionComponent;
use Polidog\Rosanna\Runtime\PsxRenderer;

/**
 * `CompileCommand` の manifest の後に動き、defer の登録を deferred manifest に書く。
 *
 * @internal
 */
final class DeferredManifestCompiler
{
    private const string GENERATED_COMMENT = '// Auto-generated by `rosanna compile`. Do not edit.';

    /**
     * @param array<string, string> $components FQCN => ソースのパス
     *
     * @return list<string> 古い (書き換えた) パス
     */
    public function compile(array $components, string $cacheDir, bool $check): array
    {
        $path = $cacheDir . \DIRECTORY_SEPARATOR . PsxRenderer::DEFERRED_MANIFEST_FILENAME;

        return $this->syncDeferredManifest($path, $components, $cacheDir, $check) ? [$path] : [];
    }

    /**
     * @param array<string, string> $components FQCN => ソースのパス
     *
     * @return bool 変更があった (`--check` なら古い) かどうか
     */
    private function syncDeferredManifest(string $path, array $components, string $cacheDir, bool $check): bool
    {
        $entries = $this->collectDeferred($components, $cacheDir);

        if ($entries === []) {
            // CP-136
            if (!\file_exists($path)) {
                return false;
            }
            if (!$check && !@\unlink($path)) {
                throw new \RuntimeException("Error: failed to remove $path");
            }

            return true;
        }

        \ksort($entries, \SORT_STRING);
        $lines = ['<?php', self::GENERATED_COMMENT, 'return ['];
        foreach ($entries as $name => $entry) {
            $lines[] = '    ' . \var_export((string) $name, true) . ' => ['
                . "'component' => " . \var_export($entry['component'], true)
                . ", 'cacheControl' => " . \var_export($entry['cacheControl'], true)
                . '],';
        }
        $lines[] = '];';

        return CompileCommand::writeIfChanged($path, \implode("\n", $lines) . "\n", $check);
    }

    /**
     * CP-135: `Defer` の文字列を含むファイルだけを読み込む。トップレベルのコードが実行される。
     *
     * @param array<string, string> $components FQCN => ソースのパス
     *
     * @return array<array-key, array{component: string, cacheControl: ?string}>
     */
    private function collectDeferred(array $components, string $cacheDir): array
    {
        \ksort($components, \SORT_STRING);

        $entries = [];
        foreach ($components as $fqcn => $file) {
            $artifactPath = CompileCommand::cachePathFor($cacheDir, $file);
            $artifact = \is_file($artifactPath) ? @\file_get_contents($artifactPath) : false;
            if ($artifact === false || !\str_contains($artifact, 'Defer')) {
                continue;
            }

            \ob_start();
            try {
                $value = require $artifactPath;
            } catch (\Throwable $e) {
                throw new \RuntimeException(
                    "Error: failed to load $artifactPath ($file) while scanning for deferred components: " . $e->getMessage(),
                    previous: $e,
                );
            } finally {
                \ob_end_clean();
            }

            if (!$value instanceof FunctionComponent || $value->defer === null) {
                continue;
            }

            $name = $value->defer->name;
            if (isset($entries[$name])) {
                throw new \RuntimeException(
                    "Error: duplicate deferred component name '$name'\n"
                    . "  registered by: {$entries[$name]['component']}\n  also by:       $fqcn",
                );
            }
            $entries[$name] = ['component' => $fqcn, 'cacheControl' => $value->defer->cacheControl];
        }

        return $entries;
    }
}
