<?php

declare(strict_types=1);

namespace Polidog\Rosanna\Psx;

use Polidog\Rosanna\Runtime\PsxRenderer;

/**
 * `rosanna compile`: ディレクトリの `.psx` をまとめてコンパイルし、manifest を作る (§7、§8)。
 */
final class CompileCommand
{
    public const DEFAULT_CACHE_SUBDIR = 'var/cache/psx';

    /**
     * 生成コードの形を変えたら上げる。usePHP の `.meta` と一致しないよう 3 から始める。
     */
    public const CACHE_VERSION = 3;

    private const string GENERATED_COMMENT = '// Auto-generated by `rosanna compile`. Do not edit.';

    private const int WATCH_INTERVAL_MICROSECONDS = 500_000;

    /**
     * @param (\Closure(array<string, string>, string, string, bool): list<string>)|null $afterManifest manifest の後に動く処理。
     *        コンポーネント (FQCN => ソースのパス)、キャッシュのディレクトリ、build ID、`--check` かどうかを受け、古い (書き換えた) パスを返す。
     *        渡さなければ、残っている deferred manifest を消す (CP-136)
     */
    public function __construct(
        private readonly ?\Closure $afterManifest = null,
    ) {}

    /**
     * @param list<string> $argv `compile` の後の引数。オプションとパスの順は問わない
     */
    public function run(array $argv, string $cwd): int
    {
        try {
            return $this->execute($argv, $cwd);
        } catch (\Throwable $e) {
            $this->println('Error: ' . $e->getMessage());

            return 1;
        }
    }

    public static function cachePathFor(string $cacheDir, string $sourcePath): string
    {
        $absolute = \realpath($sourcePath);

        return \rtrim($cacheDir, \DIRECTORY_SEPARATOR)
            . \DIRECTORY_SEPARATOR
            . \sha1($absolute === false ? $sourcePath : $absolute)
            . '.php';
    }

    public static function metaPathFor(string $cacheDir, string $sourcePath): string
    {
        return self::cachePathFor($cacheDir, $sourcePath) . '.meta';
    }

    /**
     * @param list<string> $argv
     */
    private function execute(array $argv, string $cwd): int
    {
        $check = $clean = $watch = false;
        $cache = null;
        $paths = [];

        foreach ($argv as $arg) {
            if ($arg === '--check') {
                $check = true;
            } elseif ($arg === '--clean') {
                $clean = true;
            } elseif ($arg === '--watch') {
                $watch = true;
            } elseif (\str_starts_with($arg, '--cache=') && $arg !== '--cache=') {
                $cache = \substr($arg, \strlen('--cache='));
            } elseif (\str_starts_with($arg, '-')) {
                // `--chek` で CI の検査が素通りしないように止める
                $this->println("Error: unknown option: $arg");

                return 1;
            } else {
                $paths[] = $arg;
            }
        }

        $cacheDir = $this->absolutePath($cache ?? self::DEFAULT_CACHE_SUBDIR, $cwd);

        if ($clean) {
            return $this->clean($cacheDir);
        }

        if ($check && $watch) {
            // CP-123: `--check` は書き込まないが、`--watch` は書き込み続ける。両立しないので止める
            $this->println('Error: --check and --watch cannot be used together');

            return 1;
        }

        $givenPaths = $paths === [] ? ['components'] : $paths;
        $missing = \array_filter(
            $givenPaths,
            fn(string $path): bool => !\file_exists($this->absolutePath($path, $cwd)),
        );
        if ($missing !== []) {
            $this->println('Error: path not found: ' . \implode(', ', $missing));

            return 1;
        }
        $absolutePaths = \array_map(fn(string $path): string => $this->absolutePath($path, $cwd), $givenPaths);

        if ($watch) {
            $this->watch($absolutePaths, $cacheDir);
        }

        return $this->build($absolutePaths, $cacheDir, $check);
    }

    /**
     * CP-125: 失敗しても終了せず、次の変更まで同じエラーを繰り返さない。
     *
     * @param list<string> $paths
     */
    private function watch(array $paths, string $cacheDir): never
    {
        $this->println('Watching for .psx changes (Ctrl+C to stop)...');

        $seen = null;
        // SIGINT まで動き続ける
        while (true) {
            // filemtime() の結果は PHP がキャッシュしている
            \clearstatcache();

            try {
                $current = $this->modificationTimes($paths);
            } catch (\Throwable $e) {
                $this->println('Error: ' . $e->getMessage());
                $current = $seen;
            }

            if ($current !== $seen) {
                $this->println(\date('H:i:s') . ' recompiling...');
                $this->build($paths, $cacheDir, false);
                $seen = $current;
            }

            \usleep(self::WATCH_INTERVAL_MICROSECONDS);
        }
    }

    /**
     * @param list<string> $paths
     *
     * @return array<string, int>
     */
    private function modificationTimes(array $paths): array
    {
        $times = [];
        foreach ($this->collectSourceFiles($paths) as $file) {
            $mtime = \filemtime($file);
            if ($mtime !== false) {
                $times[$file] = $mtime;
            }
        }

        return $times;
    }

    /**
     * 1 回分のコンパイル。失敗のメッセージを表示して 1 を返し、例外を外へ出さない。
     *
     * @param list<string> $paths
     */
    private function build(array $paths, string $cacheDir, bool $check): int
    {
        try {
            $files = $this->collectSourceFiles($paths);
            if ($files === []) {
                $this->println('No .psx files found in: ' . \implode(', ', $paths));

                return 0;
            }

            if (!$check) {
                $this->ensureDirectory($cacheDir);
            }

            return $this->compileFiles($files, $cacheDir, $check);
        } catch (\Throwable $e) {
            $this->println($e->getMessage());

            return 1;
        }
    }

    /**
     * @param list<string> $files
     */
    private function compileFiles(array $files, string $cacheDir, bool $check): int
    {
        $sources = [];
        /** @var array<string, string> $components FQCN => ソースのパス */
        $components = [];
        /** @var array<string, true> $known 参照の解決先 */
        $known = [];

        foreach ($files as $file) {
            $source = @\file_get_contents($file);
            if ($source === false) {
                throw new \RuntimeException("Error: cannot read $file");
            }
            $sources[$file] = $source;

            try {
                $context = NamespaceContext::fromSource(new PsxPreProcessor()->process($source)->code);
            } catch (\RuntimeException $e) {
                throw new \RuntimeException("$file: " . $e->getMessage(), previous: $e);
            }

            foreach ($context->getRuntimeDeclarations() as $declared) {
                $known[$declared] = true;
            }

            $base = \pathinfo($file, \PATHINFO_FILENAME);
            // CP-117、CP-118
            if ($base === '' || !\ctype_upper($base[0])) {
                continue;
            }

            $fqcn = $context->getNamespace() === '' ? $base : $context->getNamespace() . '\\' . $base;
            if (isset($components[$fqcn])) {
                throw new \RuntimeException(
                    "Error: duplicate component FQCN '$fqcn'\n  defined in: {$components[$fqcn]}\n  also in:    $file",
                );
            }
            $components[$fqcn] = $file;
            $known[$fqcn] = true;
        }

        $compiler = new Compiler();
        $stale = [];
        $staleArtifacts = false;
        /** @var array<string, string> $compiled ソースのパス => このコンパイルの成果物 */
        $compiled = [];
        $cachedCount = 0;

        foreach ($sources as $file => $source) {
            $artifactPath = self::cachePathFor($cacheDir, $file);
            $metaPath = self::metaPathFor($cacheDir, $file);
            $hash = \hash('sha256', self::CACHE_VERSION . "\0" . $source);

            // CP-121: 変更のないファイルでも、ほかのファイルの削除で参照が切れることがある
            $meta = $this->readMeta($metaPath);
            if ($meta !== null
                && $meta['hash'] === $hash
                && \is_file($artifactPath)
                && \array_diff($meta['refs'], \array_keys($known)) === []) {
                $cachedCount++;
                continue;
            }

            try {
                $artifact = $compiler->compile($source);
            } catch (\Throwable $e) {
                throw new \RuntimeException("$file: " . $e->getMessage(), previous: $e);
            }

            $refs = $compiler->getLastReferences();
            foreach ($refs as $ref) {
                if (!isset($known[$ref])) {
                    $short = \substr((string) \strrchr('\\' . $ref, '\\'), 1);

                    throw new \RuntimeException(
                        "$file: unresolved component '$ref'\n"
                        . "  Add a 'use' statement, define $short.psx, or declare `// @psx-runtime $ref`.",
                    );
                }
            }

            $compiled[$file] = $artifact;
            if (self::writeIfChanged($artifactPath, $artifact, $check)) {
                $stale[] = $file;
                $staleArtifacts = true;
            }

            if (!$check) {
                self::writeIfChanged(
                    $metaPath,
                    \json_encode(['hash' => $hash, 'refs' => $refs, 'source' => $file], \JSON_THROW_ON_ERROR | \JSON_UNESCAPED_SLASHES),
                    false,
                );
            }
        }

        $manifestPath = $cacheDir . \DIRECTORY_SEPARATOR . PsxRenderer::MANIFEST_FILENAME;
        $entries = $this->manifestEntries($components, $compiled, $cacheDir);
        $buildId = $this->buildId($sources, $compiled, $cacheDir, $entries);
        $manifestSource = \implode("\n", ['<?php', self::GENERATED_COMMENT, 'return [', '    ' . \var_export(PsxRenderer::BUILD_ID_KEY, true) . ' => ' . \var_export($buildId, true) . ',', ...$entries, '];']) . "\n";
        if (self::writeIfChanged($manifestPath, $manifestSource, $check)) {
            $stale[] = $manifestPath;
        }

        if ($this->afterManifest === null) {
            $deferredPath = $cacheDir . \DIRECTORY_SEPARATOR . PsxRenderer::DEFERRED_MANIFEST_FILENAME;
            if ($this->removeStaleDeferredManifest($deferredPath, $check)) {
                $stale[] = $deferredPath;
            }
        } elseif (!$staleArtifacts || !$check) {
            // `--check` で古い成果物は読み込まない。その場合はすでに exit 1 が決まっている
            $stale = [...$stale, ...($this->afterManifest)($components, $cacheDir, $buildId, $check)];
        }

        if ($check) {
            if ($stale !== []) {
                $this->println("Out of date:\n  " . \implode("\n  ", $stale));

                return 1;
            }
            $this->println('Up to date: ' . \count($files) . ' .psx file(s)');

            return 0;
        }

        $suffix = $cachedCount > 0 ? " ($cachedCount cached)" : '';
        $this->println('Compiled ' . \count($files) . " .psx file(s)$suffix -> $cacheDir");
        $this->println("Manifest: $manifestPath");

        return 0;
    }

    /**
     * @param array<string, string> $components FQCN => ソースのパス
     * @param array<string, string> $compiled ソースのパス => 成果物
     *
     * @return list<string> manifest の項目の行
     */
    private function manifestEntries(array $components, array $compiled, string $cacheDir): array
    {
        \ksort($components, \SORT_STRING);

        $parameters = new ComponentParameters();
        $lines = [];
        foreach ($components as $fqcn => $file) {
            $artifactPath = self::cachePathFor($cacheDir, $file);
            // `--check` では成果物を書かないので、今回コンパイルしたものはメモリから読む
            $artifact = $compiled[$file] ?? @\file_get_contents($artifactPath);
            $entries = \is_string($artifact) ? $parameters->collect($artifact, $fqcn) : [];

            $lines[] = '    ' . \var_export($fqcn, true) . ' => [';
            $lines[] = "        'file' => " . \var_export($artifactPath, true) . ',';
            if ($entries === []) {
                $lines[] = "        'parameters' => [],";
            } else {
                $lines[] = "        'parameters' => [";
                foreach ($entries as $entry) {
                    $pairs = [];
                    foreach ($entry as $key => $value) {
                        $pairs[] = "'$key' => " . \var_export($value, true);
                    }
                    $lines[] = '            [' . \implode(', ', $pairs) . '],';
                }
                $lines[] = '        ],';
            }
            $lines[] = '    ],';
        }

        return $lines;
    }

    /**
     * 成果物の内容から決まる ID。同じ入力なら同じ値になるので `writeIfChanged()` の判定を壊さない。
     *
     * @param array<string, string> $sources ソースのパス => ソース
     * @param array<string, string> $compiled ソースのパス => 成果物
     * @param list<string> $entries manifest の項目の行
     */
    private function buildId(array $sources, array $compiled, string $cacheDir, array $entries): string
    {
        $context = \hash_init('sha256');
        \hash_update($context, \implode("\n", $entries));
        foreach (\array_keys($sources) as $file) {
            $artifact = $compiled[$file] ?? @\file_get_contents(self::cachePathFor($cacheDir, $file));
            \hash_update($context, "\0" . $file . "\0" . (\is_string($artifact) ? $artifact : ''));
        }

        return \hash_final($context);
    }

    /**
     * CP-136: closure を渡さない compile は defer を調べないので、残っている deferred manifest は古い。
     *
     * @return bool 消した (`--check` なら古い) かどうか
     */
    private function removeStaleDeferredManifest(string $path, bool $check): bool
    {
        if (!\file_exists($path)) {
            return false;
        }
        if (!$check && !@\unlink($path)) {
            throw new \RuntimeException("Error: failed to remove $path");
        }

        return true;
    }

    /**
     * @param list<string> $paths
     *
     * @return list<string> 重複を除いてソートした絶対パス
     */
    private function collectSourceFiles(array $paths): array
    {
        $files = [];
        foreach ($paths as $path) {
            if (\is_file($path)) {
                if (\str_ends_with($path, '.psx')) {
                    $files[] = $path;
                }
                continue;
            }
            if (!\is_dir($path)) {
                continue;
            }
            $iterator = new \RecursiveIteratorIterator(
                new \RecursiveDirectoryIterator($path, \FilesystemIterator::SKIP_DOTS),
            );
            foreach ($iterator as $entry) {
                \assert($entry instanceof \SplFileInfo);
                if (!$entry->isLink() && $entry->isFile() && \str_ends_with($entry->getPathname(), '.psx')) {
                    $files[] = $entry->getPathname();
                }
            }
        }

        $absolute = \array_map(static fn(string $file): string => \realpath($file) ?: $file, $files);
        $unique = \array_values(\array_unique($absolute));
        \sort($unique);

        return $unique;
    }

    /**
     * @return array{hash: string, refs: list<string>}|null
     */
    private function readMeta(string $path): ?array
    {
        $content = \is_file($path) ? @\file_get_contents($path) : false;
        if ($content === false) {
            return null;
        }
        $data = \json_decode($content, true);
        if (!\is_array($data) || !\is_string($data['hash'] ?? null) || !\is_string($data['source'] ?? null) || !\is_array($data['refs'] ?? null)) {
            return null;
        }
        $refs = [];
        foreach ($data['refs'] as $ref) {
            if (!\is_string($ref)) {
                return null;
            }
            $refs[] = $ref;
        }

        return ['hash' => $data['hash'], 'refs' => $refs];
    }

    /**
     * CP-122: 内容が変わるときだけ、同じディレクトリの一時ファイルと rename で書く。
     * 別のリクエストが書きかけの PHP を読まないようにするため。
     *
     * @return bool 内容が変わる (変わった) かどうか
     */
    public static function writeIfChanged(string $path, string $content, bool $dryRun): bool
    {
        if (\is_file($path) && @\file_get_contents($path) === $content) {
            return false;
        }
        if ($dryRun) {
            return true;
        }

        $temporary = $path . '.' . \bin2hex(\random_bytes(6)) . '.tmp';
        if (@\file_put_contents($temporary, $content) !== \strlen($content) || !@\rename($temporary, $path)) {
            @\unlink($temporary);

            throw new \RuntimeException("Error: failed to write $path (disk full or permissions?)");
        }

        return true;
    }

    private function ensureDirectory(string $directory): void
    {
        if (!\is_dir($directory) && !@\mkdir($directory, 0o755, true) && !\is_dir($directory)) {
            throw new \RuntimeException("Error: cannot create cache directory $directory");
        }
    }

    /**
     * CP-124
     */
    private function clean(string $cacheDir): int
    {
        if (!\is_dir($cacheDir)) {
            $this->println("Cache directory does not exist: $cacheDir");

            return 0;
        }

        $removed = 0;
        $iterator = new \RecursiveIteratorIterator(
            new \RecursiveDirectoryIterator($cacheDir, \FilesystemIterator::SKIP_DOTS),
            \RecursiveIteratorIterator::CHILD_FIRST,
        );
        foreach ($iterator as $entry) {
            \assert($entry instanceof \SplFileInfo);
            $path = $entry->getPathname();
            // リンクは追わず、リンク自体を消す
            if ($entry->isDir() && !$entry->isLink()) {
                @\rmdir($path);
            } elseif (@\unlink($path)) {
                $removed++;
            } else {
                $this->println("Warning: could not remove $path");
            }
        }
        $this->println("Removed $removed file(s) from $cacheDir");

        return 0;
    }

    /**
     * `$cwd` を基準に絶対パスにする。まだない出力先は、存在する親までを正規化する。
     */
    private function absolutePath(string $path, string $cwd): string
    {
        if (!\str_starts_with($path, '/') && \preg_match('~^[A-Za-z]:[\\\\/]~', $path) !== 1) {
            $path = \rtrim($cwd, '/\\') . \DIRECTORY_SEPARATOR . $path;
        }
        $real = \realpath($path);
        if ($real !== false) {
            return $real;
        }
        $parent = \dirname($path);

        return $parent === $path ? $path : $this->absolutePath($parent, $cwd) . \DIRECTORY_SEPARATOR . \basename($path);
    }

    /**
     * CP-126: Relayer は ob_start() で捕まえている。
     */
    private function println(string $message): void
    {
        echo $message . "\n";
    }
}
